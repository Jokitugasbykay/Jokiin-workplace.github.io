const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const fixture=require('./test-allocation-fixture.json');
const context=vm.createContext({window:{},Date,Intl});
vm.runInContext(fs.readFileSync('js/monthly-cashflow.js','utf8'),context);
const date='2026-10-26T01:00:00Z';
const books=(fixture.business_bookkeeping_records||[]).map(row=>({...row,created_at:date}));
const data={books,orders:[],payments:[],checkouts:[],expenses:[],reseller:[],mayar:[{id:'confirmed',status:'success',gross_amount:252990,fee_amount:2775,net_amount:250215,confirmed_by:'admin',confirmed_at:date,transaction_reference:'audit-reference'}]};
const result=context.window.MonthlyCashflow.build(data,'2026-10');
assert.equal(result.totals.funding,400000);
assert.equal(result.totals.sales,0,'Reference sales must not fabricate receipts');
assert.equal(result.totals.repayment,0,'Outstanding personal capital is not an actual repayment');
assert.equal(result.outgoing,2775);
assert.equal(result.rows.filter(row=>row.kind==='transfer').length,1);
assert.equal(result.rows.find(row=>row.kind==='transfer').amount,250215);
assert.ok(!result.rows.some(row=>row.category==='review'),'Reference amounts stay in the existing bookkeeping panel');
assert.equal(context.window.MonthlyCashflow.build({...data,books:[],mayar:[]},'2026-10').incoming,0,'No fallback funding transactions');
console.log('PASS: actual funding, Mayar fee/transfer separated, reference sales and personal capital never fabricated as cash transactions.');
